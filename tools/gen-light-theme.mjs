// Generates ui-src/styles/theme-light.generated.css.
//
// The app's stylesheets hardcode a lot of dark neutrals. Rather than touch each
// one (and risk the dark theme), this walks them and, for every neutral
// background, border or text colour, emits a light-theme override that maps it
// onto the shared --ds-* palette. The dark theme stays byte-for-byte as it was.
//
// Run with: npm run theme:light   (re-run after adding hardcoded neutrals)

import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import postcss from 'postcss';

const DIR = fileURLToPath(new URL('../ui-src/styles/', import.meta.url));
// Windows drawn over a game keep their own dark look in every theme.
const SKIP = new Set(['replay-overlay.css', 'replay-lens.css', 'live-replay.css']);
const OUT = 'theme-light.generated.css';

const LADDER = [
  [16, '--ds-bg'], [20, '--ds-surface-deep'], [21, '--ds-surface-sunken'], [22, '--ds-recessed'],
  [26, '--ds-surface'], [34, '--ds-surface-2'], [49, '--ds-secondary'], [67, '--ds-outline'],
];

function parse(hex) {
  let h = hex.slice(1);
  if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('');
  if (h.length !== 6 && h.length !== 8) return null;
  const n = i => parseInt(h.slice(i, i + 2), 16);
  return {r: n(0), g: n(2), b: n(4), a: h.length === 8 ? h.slice(6, 8) : null};
}

function mapColor(prop, hex) {
  const c = parse(hex);
  if (!c) return null;
  const {r, g, b, a} = c;
  if (Math.max(r, g, b) - Math.min(r, g, b) >= 24) return null; // coloured: leave alone
  const isBg = prop.startsWith('background');
  const isBorder = /^(border|outline)/.test(prop);
  const isText = prop === 'color';
  const L = (r + g + b) / 3;
  if (a !== null) {
    // A faint light veil over a dark surface (hover tint, hairline) becomes a faint
    // dark one over a light surface. Strong veils sit on media and stay as they are.
    if (L >= 224 && (isBg || isBorder) && parseInt(a, 16) <= 0x40) return `#000000${a}`;
    return null;
  }
  if (isBg) {
    if (L < 10) return null; // video black stays black
    if (L <= 75) return `var(${LADDER.reduce((best, cur) => (Math.abs(cur[0] - L) < Math.abs(best[0] - L) ? cur : best))[1]})`;
    if (L <= 150) return 'var(--ds-outline)';
    return null;
  }
  if (isBorder) {
    if (L < 10) return null;
    if (L <= 58) return 'var(--ds-border)';
    if (L <= 110) return 'var(--ds-outline)';
    return null;
  }
  if (isText) {
    if (r === 255 && g === 255 && b === 255) return null; // white on accent fills stays white
    if (L >= 190) return 'var(--ds-text)';
    if (L >= 120) return 'var(--ds-text-muted)';
    return 'var(--ds-text-dim)';
  }
  return null;
}

const PROPS = /^(background(-color|-image)?|border(-(top|right|bottom|left|inline|block)[\w-]*)?(-color)?|outline(-color)?|color)$/;
const HEX = /#[0-9a-fA-F]{3,8}\b/g;
const ACCENT_TEXT = /var\(--(studio-accent|color-accent|color-text-accent)\)/g;

const out = [];
for (const file of readdirSync(DIR).filter(f => f.endsWith('.css') && !SKIP.has(f) && !f.startsWith('theme-light')).sort()) {
  const root = postcss.parse(readFileSync(join(DIR, file), 'utf8'));
  root.walkRules(rule => {
    if (rule.selector.includes(':root')) return;
    for (let p = rule.parent; p && p.type !== 'root'; p = p.parent) {
      if (p.type === 'atrule' && /keyframes/.test(p.name)) return;
    }
    const decls = [];
    rule.walkDecls(decl => {
      // Accent-coloured text is darkened on the grey theme; fills keep the exact accent.
      if (decl.prop === 'color' && new RegExp(ACCENT_TEXT.source).test(decl.value)) {
        decls.push(`color:${decl.value.replace(ACCENT_TEXT, 'var(--studio-accent-text)')}${decl.important ? '!important' : ''}`);
        return;
      }
      if (!PROPS.test(decl.prop) || !HEX.test(decl.value)) return;
      HEX.lastIndex = 0;
      let changed = false;
      const value = decl.value.replace(HEX, hex => {
        const mapped = mapColor(decl.prop, hex);
        if (mapped) changed = true;
        return mapped ?? hex;
      });
      if (changed) decls.push(`${decl.prop}:${value}${decl.important ? '!important' : ''}`);
    });
    if (!decls.length) return;
    const selector = rule.selectors.map(s => `html[data-theme='light'] ${s.trim()}`).join(',');
    let text = `${selector}{${decls.join(';')}}`;
    for (let p = rule.parent; p && p.type !== 'root'; p = p.parent) {
      if (p.type === 'atrule') text = `@${p.name} ${p.params}{${text}}`;
    }
    out.push(text);
  });
}

writeFileSync(join(DIR, OUT), `/* Generated by tools/gen-light-theme.mjs. Do not edit; run \`npm run theme:light\`. */\n${out.join('\n')}\n`);
console.log(`${OUT}: ${out.length} rules`);
